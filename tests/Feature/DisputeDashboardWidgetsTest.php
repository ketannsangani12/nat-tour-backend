<?php

namespace Tests\Feature;

use Tests\TestCase;
use App\Models\Dispute;
use App\Models\Admin;
use App\Services\Dispute\DisputeNotificationService;
use Illuminate\Foundation\Testing\WithFaker;
use Illuminate\Support\Facades\DB;

/**
 * DisputeDashboardWidgetsTest
 * 
 * Tests the dispute dashboard widgets functionality including:
 * - Dashboard data API endpoint
 * - Widget data accuracy
 * - Permission-based access
 * - Real-time updates
 * 
 * Requirements: 8.6
 */
class DisputeDashboardWidgetsTest extends TestCase
{
    use WithFaker;

    protected Admin $admin;
    protected DisputeNotificationService $notificationService;

    /**
     * tests/TestCase.php runs against the real tenant DB with no transaction/rollback
     * wrapper, so every Admin::factory()/Dispute::factory() row created here (and the
     * TourBooking/Transaction rows Dispute::factory() cascades into when booking_id/
     * transaction_id aren't overridden) is a real, permanent write unless torn down
     * explicitly. Track every id created by this test class so tearDown() can remove
     * the full dependent chain after each test method.
     */
    protected array $createdAdminIds = [];
    protected array $createdBookingIds = [];
    protected array $createdTransactionIds = [];
    protected array $createdDisputeIds = [];

    protected function setUp(): void
    {
        parent::setUp();

        \Spatie\Permission\Models\Permission::firstOrCreate(['name' => 'view-payment-dispute', 'guard_name' => 'admin']);

        // Clear rate limiter state accumulated from previous tests in the same run
        \Illuminate\Support\Facades\RateLimiter::clear('dispute_view|127.0.0.1');
        \Illuminate\Support\Facades\RateLimiter::clear('dispute_modify|127.0.0.1');

        // Clean up dispute records so count-based assertions are not polluted by other tests
        \Illuminate\Support\Facades\DB::table('dispute_timeline')->delete();
        \Illuminate\Support\Facades\DB::table('dispute_evidence')->delete();
        \Illuminate\Support\Facades\DB::table('disputes')->delete();

        $this->admin = Admin::factory()->create();
        $this->createdAdminIds[] = $this->admin->id;
        $this->admin->givePermissionTo('view-payment-dispute');

        $this->notificationService = app(DisputeNotificationService::class);
    }

    /**
     * Track ids generated by a bare Dispute::factory()->create()/count(N)->create()
     * call (i.e. one that didn't explicitly override booking_id/transaction_id, so
     * the factory cascaded into new TourBooking/Transaction rows) so tearDown() can
     * clean them up. Accepts a single Dispute model or a Collection from ->count(N).
     */
    private function trackDispute($disputes): void
    {
        $disputes = $disputes instanceof \Illuminate\Support\Collection || $disputes instanceof \Illuminate\Database\Eloquent\Collection
            ? $disputes
            : collect([$disputes]);

        foreach ($disputes as $dispute) {
            $this->createdDisputeIds[] = $dispute->id;
            if ($dispute->booking_id) {
                $this->createdBookingIds[] = $dispute->booking_id;
            }
            if ($dispute->transaction_id) {
                $this->createdTransactionIds[] = $dispute->transaction_id;

                // TransactionFactory's own default 'tour_booking_id' => TourBooking::factory()
                // cascades a SEPARATE booking from the dispute's own booking_id, since Laravel
                // resolves each nested factory independently.
                $transactionBookingId = DB::table('transactions')->where('id', $dispute->transaction_id)->value('tour_booking_id');
                if ($transactionBookingId) {
                    $this->createdBookingIds[] = $transactionBookingId;
                }
            }
        }
    }

    protected function tearDown(): void
    {
        if (!empty($this->createdDisputeIds) || !empty($this->createdBookingIds)) {
            DB::table('disputes')
                ->where(function ($query) {
                    if (!empty($this->createdDisputeIds)) {
                        $query->orWhereIn('id', $this->createdDisputeIds);
                    }
                    if (!empty($this->createdBookingIds)) {
                        $query->orWhereIn('booking_id', $this->createdBookingIds);
                    }
                })
                ->delete();
        }

        if (!empty($this->createdTransactionIds) || !empty($this->createdBookingIds)) {
            DB::table('transactions')
                ->where(function ($query) {
                    if (!empty($this->createdTransactionIds)) {
                        $query->orWhereIn('id', $this->createdTransactionIds);
                    }
                    if (!empty($this->createdBookingIds)) {
                        $query->orWhereIn('tour_booking_id', $this->createdBookingIds);
                    }
                })
                ->delete();
        }

        if (!empty($this->createdBookingIds)) {
            DB::table('tour_bookings_transact')->whereIn('tour_booking_id', $this->createdBookingIds)->delete();
            DB::table('tour_booking_history')->whereIn('tour_booking_id', $this->createdBookingIds)->delete();
            DB::table('tour_bookings_master')->whereIn('id', $this->createdBookingIds)->delete();
        }

        if (!empty($this->createdAdminIds)) {
            DB::table('admins')->whereIn('id', $this->createdAdminIds)->delete();
        }

        parent::tearDown();
    }

    /** @test */
    public function it_returns_dashboard_data_for_authorized_users()
    {
        // Create test disputes
        $this->trackDispute(Dispute::factory()->create([
            'status' => 'warning_needs_response',
            'evidence_due_by' => now()->addDays(2)
        ]));

        $this->trackDispute(Dispute::factory()->create([
            'status' => 'under_review',
            'evidence_due_by' => now()->addHours(12)
        ]));

        $response = $this->actingAs($this->admin, 'admin')
            ->getJson(route('admin.disputes.dashboard-data'));

        $response->assertStatus(200)
            ->assertJsonStructure([
                'active_disputes',
                'urgent_disputes', 
                'overdue_disputes',
                'total_disputes',
                'status_breakdown',
                'metrics' => [
                    'win_rate',
                    'response_rate',
                    'avg_response_time'
                ],
                'last_updated'
            ]);
    }

    /** @test */
    public function it_denies_access_to_unauthorized_users()
    {
        $unauthorizedAdmin = Admin::factory()->create();
        $this->createdAdminIds[] = $unauthorizedAdmin->id;

        $response = $this->actingAs($unauthorizedAdmin, 'admin')
            ->getJson(route('admin.disputes.dashboard-data'));

        $response->assertStatus(403);
    }

    /** @test */
    public function it_calculates_dispute_counts_correctly()
    {
        // Create active disputes with no deadline (should not count as urgent)
        $this->trackDispute(Dispute::factory()->count(3)->create([
            'status' => 'warning_needs_response',
            'evidence_due_by' => null
        ]));

        // Create urgent disputes (due within 3 days)
        $this->trackDispute(Dispute::factory()->count(2)->create([
            'status' => 'warning_needs_response',
            'evidence_due_by' => now()->addDays(2)
        ]));

        // Create overdue disputes
        $this->trackDispute(Dispute::factory()->create([
            'status' => 'warning_needs_response',
            'evidence_due_by' => now()->subDay()
        ]));

        $summary = $this->notificationService->getDisputeSummary();

        $this->assertEquals(6, $summary['active_disputes']); // all 6 are warning_needs_response
        $this->assertEquals(3, $summary['urgent_disputes']); // 2 due in 2 days + 1 overdue (<=now+3)
        $this->assertEquals(1, $summary['overdue_disputes']);
        $this->assertEquals(6, $summary['total_disputes']);
    }

    /** @test */
    public function it_provides_status_breakdown()
    {
        $this->trackDispute(Dispute::factory()->count(2)->create(['status' => 'warning_needs_response']));
        $this->trackDispute(Dispute::factory()->create(['status' => 'under_review']));
        $this->trackDispute(Dispute::factory()->create(['status' => 'won']));
        $this->trackDispute(Dispute::factory()->create(['status' => 'lost']));

        $summary = $this->notificationService->getDisputeSummary();

        $this->assertArrayHasKey('status_breakdown', $summary);
        $this->assertEquals(2, $summary['status_breakdown']['warning_needs_response']);
        $this->assertEquals(1, $summary['status_breakdown']['under_review']);
        $this->assertEquals(1, $summary['status_breakdown']['won']);
        $this->assertEquals(1, $summary['status_breakdown']['lost']);
    }

    /** @test */
    public function it_calculates_metrics_correctly()
    {
        // Create resolved disputes for win rate calculation
        $this->trackDispute(Dispute::factory()->count(3)->create(['status' => 'won']));
        $this->trackDispute(Dispute::factory()->count(2)->create(['status' => 'lost']));

        // Create overdue dispute for response rate
        $this->trackDispute(Dispute::factory()->create([
            'status' => 'warning_needs_response',
            'evidence_due_by' => now()->subDay()
        ]));

        $summary = $this->notificationService->getDisputeSummary();

        $this->assertArrayHasKey('metrics', $summary);
        $this->assertEquals('60%', $summary['metrics']['win_rate']); // 3 won out of 5 resolved
        $this->assertEquals('83.3%', $summary['metrics']['response_rate']); // 5 out of 6 not overdue
    }

    /** @test */
    public function it_handles_empty_dispute_data_gracefully()
    {
        $summary = $this->notificationService->getDisputeSummary();

        $this->assertEquals(0, $summary['active_disputes']);
        $this->assertEquals(0, $summary['urgent_disputes']);
        $this->assertEquals(0, $summary['overdue_disputes']);
        $this->assertEquals(0, $summary['total_disputes']);
        $this->assertEquals('N/A', $summary['metrics']['win_rate']);
        $this->assertEquals('N/A', $summary['metrics']['response_rate']);
    }

    /** @test */
    public function dashboard_widgets_render_correctly()
    {
        $this->trackDispute(Dispute::factory()->count(2)->create([
            'status' => 'warning_needs_response',
            'evidence_due_by' => now()->addDays(2)
        ]));

        $response = $this->actingAs($this->admin, 'admin')
            ->withSession(['userType' => 'Admin', '_token' => csrf_token()])
            ->get(route('admin.disputes.index'));

        $response->assertStatus(200)
            ->assertSee('Payment Disputes')
            ->assertSee('Active Disputes')
            ->assertSee('Urgent')
            ->assertSee('Total Disputes');
    }
}