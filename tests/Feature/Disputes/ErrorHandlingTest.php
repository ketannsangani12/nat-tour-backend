<?php

namespace Tests\Feature\Disputes;

use Tests\TestCase;
use App\Services\Dispute\StripeErrorHandler;
use App\Services\Dispute\DisputeAuditLogger;
use App\Services\Dispute\PciComplianceService;
use App\Models\Admin;
use Illuminate\Support\Facades\Log;
use Illuminate\Support\Facades\Cache;
use Stripe\Exception\RateLimitException;
use Stripe\Exception\AuthenticationException;
use Stripe\Exception\InvalidRequestException;
use Illuminate\Support\Facades\DB;
use Mockery;

/**
 * ErrorHandlingTest
 *
 * Tests comprehensive error handling and security measures for dispute management.
 *
 * Requirements: 3.6, 3.7, 7.7, 9.3, 9.7
 */
class ErrorHandlingTest extends TestCase
{

    protected StripeErrorHandler $errorHandler;
    protected DisputeAuditLogger $auditLogger;
    protected PciComplianceService $pciService;
    protected Admin $admin;

    /**
     * tests/TestCase.php runs against the real tenant DB with no transaction/rollback
     * wrapper, so every Admin::factory()/Dispute::factory() row created here (and the
     * TourBooking/Transaction rows Dispute::factory() cascades into when booking_id/
     * transaction_id aren't overridden) is a real, permanent write unless torn down
     * explicitly. Track every id created by this test class so tearDown() can remove
     * the full dependent chain after each test method.
     */
    protected array $createdAdminIds = [];
    protected array $createdBookingIds = [];
    protected array $createdTransactionIds = [];
    protected array $createdDisputeIds = [];

    protected function setUp(): void
    {
        parent::setUp();

        $this->errorHandler = app(StripeErrorHandler::class);
        $this->auditLogger = app(DisputeAuditLogger::class);
        $this->pciService = app(PciComplianceService::class);

        // Create test admin
        $this->admin = Admin::factory()->create();
        $this->createdAdminIds[] = $this->admin->id;
        $this->actingAs($this->admin, 'admin');
    }

    /**
     * Track ids generated by a bare Dispute::factory()->create() call (i.e. one that
     * didn't explicitly override booking_id/transaction_id, so the factory cascaded
     * into new TourBooking/Transaction rows) so tearDown() can clean them up.
     */
    private function trackDispute($dispute): void
    {
        $this->createdDisputeIds[] = $dispute->id;
        if ($dispute->booking_id) {
            $this->createdBookingIds[] = $dispute->booking_id;
        }
        if ($dispute->transaction_id) {
            $this->createdTransactionIds[] = $dispute->transaction_id;

            // TransactionFactory's own default 'tour_booking_id' => TourBooking::factory()
            // cascades a SEPARATE booking from the dispute's own booking_id, since Laravel
            // resolves each nested factory independently.
            $transactionBookingId = DB::table('transactions')->where('id', $dispute->transaction_id)->value('tour_booking_id');
            if ($transactionBookingId) {
                $this->createdBookingIds[] = $transactionBookingId;
            }
        }
    }

    /**
     * Test exponential backoff retry mechanism for rate limits.
     */
    public function test_exponential_backoff_retry_mechanism(): void
    {
        // Each RateLimitException retry logs warning twice:
        // once in handleRateLimitError + once in the retry loop
        Log::shouldReceive('warning')->times(4);

        $attempt = 0;
        $operation = function () use (&$attempt) {
            $attempt++;
            if ($attempt < 3) {
                throw new RateLimitException('Rate limit exceeded');
            }
            return ['success' => true];
        };

        $result = $this->errorHandler->executeWithErrorHandling(
            $operation,
            ['operation_type' => 'test_operation']
        );

        $this->assertEquals(['success' => true], $result);
        $this->assertEquals(3, $attempt);
    }

    /**
     * Test authentication error handling and logging.
     */
    public function test_authentication_error_handling(): void
    {
        Log::shouldReceive('error')->once()->with(
            'Stripe authentication failed - SECURITY ALERT',
            Mockery::type('array')
        );

        $operation = function () {
            throw new AuthenticationException('Invalid API key');
        };

        $this->expectException(\Exception::class);
        $this->expectExceptionMessage('Stripe authentication failed');

        $this->errorHandler->executeWithErrorHandling(
            $operation,
            ['operation_type' => 'test_auth']
        );
    }

    /**
     * Test fallback data display for API failures.
     */
    public function test_fallback_data_display(): void
    {
        // Create a real dispute so the repository can find it as fallback
        \App\Models\Dispute::where('stripe_dispute_id', 'dp_test123')->delete();
        $this->trackDispute(\App\Models\Dispute::factory()->create([
            'stripe_dispute_id' => 'dp_test123',
            'amount' => 50.00,
            'currency' => 'USD',
            'reason' => 'fraudulent',
            'status' => 'warning_needs_response',
            'evidence_due_by' => now()->addDays(7),
        ]));

        Log::shouldReceive('error')->atLeast()->once();

        $operation = function () {
            throw new InvalidRequestException('API error');
        };

        $result = $this->errorHandler->executeWithErrorHandling(
            $operation,
            [
                'operation_type' => 'dispute_retrieve',
                'dispute_id' => 'dp_test123'
            ],
            true // Enable fallback
        );

        $this->assertIsArray($result);
        $this->assertEquals('dp_test123', $result['id']);
        $this->assertTrue($result['fallback']);
    }

    /**
     * Test comprehensive activity logging with user identification.
     */
    public function test_comprehensive_activity_logging(): void
    {
        $dispute = \App\Models\Dispute::factory()->create();
        $this->trackDispute($dispute);

        $this->auditLogger->logDisputeAccess($dispute, 'dispute_viewed', [
            'view_type' => 'web',
            'includes_timeline' => true
        ]);

        // Verify audit trail record was created
        $this->assertDatabaseHas('dispute_audit_trail', [
            'event_type' => 'dispute_access',
            'dispute_id' => $dispute->id,
            'user_id' => $this->admin->id
        ]);
    }

    /**
     * Test PCI compliance measures for sensitive data protection.
     */
    public function test_pci_compliance_sensitive_data_detection(): void
    {
        $textWithCardData = 'Customer paid with card 4111111111111111 and CVV 123';

        $assessment = $this->pciService->scanForSensitiveData($textWithCardData);

        $this->assertEquals('non_compliant', $assessment['compliance_status']);
        $this->assertEquals('critical', $assessment['overall_risk_level']);
        $this->assertTrue($assessment['requires_remediation']);
        $this->assertNotEmpty($assessment['findings']);

        // Check that PAN and CVV were detected
        $findingTypes = array_column($assessment['findings'], 'type');
        $this->assertContains('pan', $findingTypes);
        $this->assertContains('sensitive_auth_data', $findingTypes);
    }

    /**
     * Test sensitive data redaction for PCI compliance.
     */
    public function test_sensitive_data_redaction(): void
    {
        $originalText = 'Payment made with card 4111111111111111, CVV: 123, customer John Doe';

        $redactionResult = $this->pciService->redactSensitiveData($originalText);

        $this->assertNotEquals($originalText, $redactionResult['redacted_text']);
        $this->assertStringNotContainsString('4111111111111111', $redactionResult['redacted_text']);
        $this->assertStringNotContainsString('CVV: 123', $redactionResult['redacted_text']);
        $this->assertStringContainsString('411111', $redactionResult['redacted_text']); // First 6 digits
        $this->assertStringContainsString('1111', $redactionResult['redacted_text']); // Last 4 digits
        $this->assertGreaterThan(0, $redactionResult['redaction_count']);
    }

    /**
     * Test audit trail maintenance and compliance reporting.
     */
    public function test_audit_trail_maintenance_and_reporting(): void
    {
        $dispute = \App\Models\Dispute::factory()->create();
        $this->trackDispute($dispute);

        // Log multiple activities
        $this->auditLogger->logDisputeAccess($dispute, 'dispute_viewed');
        $this->auditLogger->logDisputeModification($dispute, 'status_change', [
            'status' => ['from' => 'warning_needs_response', 'to' => 'under_review']
        ]);
        $this->auditLogger->logEvidenceSubmission($dispute, ['receipt' => 'test_receipt.pdf']);

        // Generate compliance report
        $startDate = now()->subDay();
        $endDate = now()->addDay();

        $report = $this->auditLogger->generateComplianceReport($startDate, $endDate);

        $this->assertArrayHasKey('summary', $report);
        $this->assertArrayHasKey('detailed_events', $report);
        $this->assertGreaterThan(0, $report['summary']['total_events']);
        $this->assertArrayHasKey('event_breakdown', $report['summary']);
        $this->assertArrayHasKey('user_activity', $report['summary']);
    }

    /**
     * Test rate limiting handling with exponential backoff.
     */
    public function test_rate_limiting_with_exponential_backoff(): void
    {
        // Clear any existing rate limit flags
        Cache::flush();

        // Each RateLimitException retry logs warning twice (handleRateLimitError + retry loop)
        Log::shouldReceive('warning')->times(6);

        $attempt = 0;
        $operation = function () use (&$attempt) {
            $attempt++;
            if ($attempt <= 3) {
                throw new RateLimitException('Rate limit exceeded');
            }
            return ['success' => true];
        };

        $startTime = microtime(true);

        $result = $this->errorHandler->executeWithErrorHandling(
            $operation,
            ['operation_type' => 'test_rate_limit']
        );

        $endTime = microtime(true);
        $executionTime = $endTime - $startTime;

        $this->assertEquals(['success' => true], $result);
        $this->assertEquals(4, $attempt);
        // Should have some delay due to exponential backoff
        $this->assertGreaterThan(3, $executionTime); // At least 3 seconds of backoff
    }

    /**
     * Test security event logging and monitoring.
     */
    public function test_security_event_logging(): void
    {
        $dispute = \App\Models\Dispute::factory()->create();
        $this->trackDispute($dispute);

        // logSecurityEvent uses Log::log('alert', ...) not Log::alert() for the first call
        Log::shouldReceive('log')->once()->with(
            'alert',
            'Security event logged',
            Mockery::type('array')
        );

        Log::shouldReceive('alert')->once()->with(
            'CRITICAL SECURITY EVENT - Security team notification required',
            Mockery::type('array')
        );

        $this->auditLogger->logSecurityEvent($dispute, 'unauthorized_access', [
            'attempted_action' => 'view_sensitive_data',
            'blocked' => true
        ]);

        // Verify security event was logged in audit trail
        $this->assertDatabaseHas('dispute_audit_trail', [
            'event_type' => 'security_event',
            'dispute_id' => $dispute->id,
            'user_id' => $this->admin->id,
            'risk_level' => 'critical'
        ]);
    }

    /**
     * Test data encryption for sensitive information.
     */
    public function test_data_encryption_for_sensitive_information(): void
    {
        $sensitiveData = 'Customer SSN: 123-45-6789, Card: 4111111111111111';

        $encryptionResult = $this->pciService->encryptSensitiveData($sensitiveData, [
            'data_type' => 'sensitive_data',
            'source' => 'evidence_upload'
        ]);

        $this->assertArrayHasKey('encrypted_data', $encryptionResult);
        $this->assertArrayHasKey('encryption_method', $encryptionResult);
        $this->assertArrayHasKey('data_hash', $encryptionResult);
        $this->assertNotEquals($sensitiveData, $encryptionResult['encrypted_data']);

        // Test decryption
        $decryptedData = $this->pciService->decryptSensitiveData(
            $encryptionResult['encrypted_data'],
            ['access_reason' => 'compliance_audit']
        );

        $this->assertEquals($sensitiveData, $decryptedData);
    }

    /**
     * Test file upload security and PCI compliance.
     */
    public function test_file_upload_security_and_pci_compliance(): void
    {
        // Create a test file with sensitive content
        $fileContent = "Receipt for payment\nCard Number: 4111111111111111\nCVV: 123\nAmount: $50.00";
        $tempFile = tmpfile();
        fwrite($tempFile, $fileContent);
        $tempPath = stream_get_meta_data($tempFile)['uri'];

        $uploadedFile = new \Illuminate\Http\UploadedFile(
            $tempPath,
            'receipt.txt',
            'text/plain',
            null,
            true
        );

        $storageResult = $this->pciService->securelyStoreEvidenceFile($uploadedFile, [
            'dispute_id' => 1,
            'evidence_type' => 'receipt'
        ]);

        $this->assertArrayHasKey('secure_path', $storageResult);
        $this->assertArrayHasKey('is_encrypted', $storageResult);
        $this->assertArrayHasKey('compliance_scan', $storageResult);
        $this->assertTrue($storageResult['is_encrypted']); // Should be encrypted due to sensitive data
        $this->assertEquals('non_compliant', $storageResult['compliance_scan']['compliance_status']);

        fclose($tempFile);
    }

    /**
     * Test authentication failure tracking and alerting.
     */
    public function test_authentication_failure_tracking(): void
    {
        // Clean up any leftover authentication_failure records from previous runs
        \DB::table('dispute_audit_trail')->where('event_type', 'authentication_failure')->delete();

        // logAuthenticationFailure calls Log::log('critical', ...) not Log::alert()
        Log::shouldReceive('log')->withAnyArgs();
        // trackRepeatedFailures triggers Log::alert at failures >= 5 (calls 5 and 6)
        Log::shouldReceive('alert')->times(2);

        // Simulate multiple authentication failures
        for ($i = 0; $i < 6; $i++) {
            $this->auditLogger->logAuthenticationFailure('invalid_credentials', [
                'attempted_username' => 'test@example.com',
                'repeated_attempts' => $i + 1
            ]);
        }

        // Verify failures are tracked — count only authentication_failure records
        // to avoid interference from other tests that may insert different event types
        $this->assertEquals(6, \DB::table('dispute_audit_trail')
            ->where('event_type', 'authentication_failure')
            ->count());

        // Check that the last failure has high risk assessment
        $lastFailure = \DB::table('dispute_audit_trail')
            ->where('event_type', 'authentication_failure')
            ->orderBy('created_at', 'desc')
            ->first();

        $this->assertEquals('high', $lastFailure->risk_level);
    }

    /**
     * Test compliance report generation.
     */
    public function test_compliance_report_generation(): void
    {
        $startDate = now()->subWeek();
        $endDate = now();

        $report = $this->pciService->generateComplianceReport($startDate, $endDate);

        $this->assertArrayHasKey('report_period', $report);
        $this->assertArrayHasKey('compliance_requirements', $report);
        $this->assertArrayHasKey('data_protection_measures', $report);
        $this->assertArrayHasKey('security_incidents', $report);
        $this->assertArrayHasKey('compliance_score', $report);
        $this->assertArrayHasKey('compliance_status', $report);

        $this->assertEquals($startDate->toISOString(), $report['report_period']['start_date']);
        $this->assertEquals($endDate->toISOString(), $report['report_period']['end_date']);
        $this->assertIsFloat($report['compliance_score']);
        $this->assertIsString($report['compliance_status']);
    }

    protected function tearDown(): void
    {
        Mockery::close();

        // dispute_audit_trail.dispute_id has no FK constraint (plain indexed column),
        // so rows tied to a tracked dispute won't be removed by the disputes cascade
        // below — delete them explicitly first.
        if (!empty($this->createdDisputeIds)) {
            DB::table('dispute_audit_trail')->whereIn('dispute_id', $this->createdDisputeIds)->delete();
        }

        // test_authentication_failure_tracking() logs generic security events with no
        // dispute_id at all, so the cleanup above can't catch them — mirror that test's
        // own "clean up leftovers from previous runs" delete here too.
        DB::table('dispute_audit_trail')->where('event_type', 'authentication_failure')->delete();

        if (!empty($this->createdDisputeIds) || !empty($this->createdBookingIds)) {
            DB::table('disputes')
                ->where(function ($query) {
                    if (!empty($this->createdDisputeIds)) {
                        $query->orWhereIn('id', $this->createdDisputeIds);
                    }
                    if (!empty($this->createdBookingIds)) {
                        $query->orWhereIn('booking_id', $this->createdBookingIds);
                    }
                })
                ->delete();
        }

        if (!empty($this->createdTransactionIds) || !empty($this->createdBookingIds)) {
            DB::table('transactions')
                ->where(function ($query) {
                    if (!empty($this->createdTransactionIds)) {
                        $query->orWhereIn('id', $this->createdTransactionIds);
                    }
                    if (!empty($this->createdBookingIds)) {
                        $query->orWhereIn('tour_booking_id', $this->createdBookingIds);
                    }
                })
                ->delete();
        }

        if (!empty($this->createdBookingIds)) {
            DB::table('tour_bookings_transact')->whereIn('tour_booking_id', $this->createdBookingIds)->delete();
            DB::table('tour_booking_history')->whereIn('tour_booking_id', $this->createdBookingIds)->delete();
            DB::table('tour_bookings_master')->whereIn('id', $this->createdBookingIds)->delete();
        }

        if (!empty($this->createdAdminIds)) {
            DB::table('admins')->whereIn('id', $this->createdAdminIds)->delete();
        }

        parent::tearDown();
    }
}
