    public function test_skips_non_significant_status_changes()
    {
        Notification::fake();

        // Create admin user with permission
        $admin = Admin::factory()->create(['status' => 'active', 'email' => 'admin@test.com']);
        $this->createdAdminIds[] = $admin->id;
        $admin->givePermissionTo('view-payment-dispute');

        // Create dispute
        $dispute = Dispute::factory()->create();
        $this->trackDispute($dispute);

        // Try to send notification for non-significant status change
        $count = $this->notificationService->sendStatusChangeNotification(
            $dispute, 
            'under_review', 
            'under_review' // Same status - not significant
        );

        // Assert no notification was sent
        $this->assertEquals(0, $count);
        
        Notification::assertNotSentTo($admin, DisputeStatusChangedNotification::class);
    }

    public function test_returns_zero_when_no_recipients()
    {
        Notification::fake();

        // The tenant DB ships with users who hold the view-payment-dispute
        // permission via role, so a live query can't produce an empty recipient
        // set. Exercise the "no recipients" branch directly with a partial mock.
        $service = Mockery::mock(DisputeNotificationService::class)->makePartial();
        $service->shouldAllowMockingProtectedMethods();
        $service->shouldReceive('getNotificationRecipients')
            ->andReturn(new \Illuminate\Database\Eloquent\Collection());

        $dispute = Dispute::factory()->create();
        $this->trackDispute($dispute);

        $count = $service->sendNewDisputeNotification($dispute);

        $this->assertEquals(0, $count);
        Notification::assertNothingSent();
    }

    public function test_gets_dispute_summary()
    {
        // Clean up any pre-existing disputes so counts are deterministic
        \Illuminate\Support\Facades\DB::table('dispute_timeline')->delete();
        \Illuminate\Support\Facades\DB::table('dispute_evidence')->delete();
        \Illuminate\Support\Facades\DB::table('disputes')->delete();

        // DisputeFactory's default evidence_due_by is a random optional date, so
        // pin it explicitly here to keep urgent/overdue counts deterministic.
        $this->trackDispute(Dispute::factory()->create(['status' => 'warning_needs_response', 'evidence_due_by' => null]));
        $this->trackDispute(Dispute::factory()->create(['status' => 'under_review', 'evidence_due_by' => null]));
        $this->trackDispute(Dispute::factory()->create(['status' => 'won', 'evidence_due_by' => null]));

        $this->trackDispute(Dispute::factory()->create([
            'status' => 'warning_needs_response',
            'evidence_due_by' => now()->addDays(2),
        ]));

        $this->trackDispute(Dispute::factory()->create([
            'status' => 'warning_needs_response',
            'evidence_due_by' => now()->subDay(),
        ]));

        $summary = $this->notificationService->getDisputeSummary();

        $this->assertEquals(4, $summary['active_disputes']); // 3 warning_needs_response + 1 under_review
        $this->assertEquals(2, $summary['urgent_disputes']); // Both warning_needs_response with due dates <= 3 days
        $this->assertEquals(1, $summary['overdue_disputes']); // Past due date
        $this->assertEquals(5, $summary['total_disputes']); // All disputes
        $this->assertArrayHasKey('last_updated', $summary);
    }

    public function test_identifies_significant_status_changes()
    {
        $service = $this->notificationService;
        
        // Use reflection to test the protected method
        $reflection = new \ReflectionClass($service);
        $method = $reflection->getMethod('isSignificantStatusChange');
        $method->setAccessible(true);

        // Test significant changes
        $this->assertTrue($method->invoke($service, 'warning_needs_response', 'under_review'));
        $this->assertTrue($method->invoke($service, 'under_review', 'won'));
        $this->assertTrue($method->invoke($service, 'under_review', 'lost'));
        $this->assertTrue($method->invoke($service, 'warning_needs_response', 'lost'));

        // Test non-significant changes
        $this->assertFalse($method->invoke($service, 'under_review', 'under_review'));
        $this->assertFalse($method->invoke($service, 'warning_needs_response', 'warning_needs_response'));
    }
}