<?php

namespace Tests\Unit\Services;

use App\Models\Admin;
use App\Models\Dispute;
use App\Services\Dispute\DisputeNotificationService;
use Illuminate\Support\Facades\Notification;
use Tests\TestCase;
use Illuminate\Support\Facades\DB;
use Mockery;

class DisputeNotificationServiceTest extends TestCase
{
    protected DisputeNotificationService $notificationService;

    /**
     * tests/TestCase.php runs against the real tenant DB with no transaction/rollback
     * wrapper, so every Admin::factory()/Dispute::factory() row created here (and the
     * TourBooking/Transaction rows Dispute::factory() cascades into when booking_id/
     * transaction_id aren't overridden) is a real, permanent write unless torn down
     * explicitly. Track every id created by this test class so tearDown() can remove
     * the full dependent chain after each test method.
     */
    protected array $createdAdminIds = [];
    protected array $createdBookingIds = [];
    protected array $createdTransactionIds = [];
    protected array $createdDisputeIds = [];

    protected function setUp(): void
    {
        parent::setUp();

        $this->notificationService = app(DisputeNotificationService::class);

        $viewPerm = \Spatie\Permission\Models\Permission::firstOrCreate(
            ['name' => 'view-payment-dispute', 'guard_name' => 'admin']
        );
        $viewPermStaff = \Spatie\Permission\Models\Permission::firstOrCreate(
            ['name' => 'view-payment-dispute', 'guard_name' => 'web']
        );

        // Revoke the permission from every existing model so notification counts
        // in this file are deterministic. Seeded/leftover admins otherwise pollute
        // recipient lookup in getNotificationRecipients().
        \Illuminate\Support\Facades\DB::table('model_has_permissions')
            ->whereIn('permission_id', [$viewPerm->id, $viewPermStaff->id])
            ->delete();
    }

    /**
     * Track ids generated by a bare Dispute::factory()->create() call (i.e. one that
     * didn't explicitly override booking_id/transaction_id, so the factory cascaded
     * into new TourBooking/Transaction rows) so tearDown() can clean them up.
     */
    private function trackDispute($dispute): void
    {
        $this->createdDisputeIds[] = $dispute->id;
        if ($dispute->booking_id) {
            $this->createdBookingIds[] = $dispute->booking_id;
        }
        if ($dispute->transaction_id) {
            $this->createdTransactionIds[] = $dispute->transaction_id;

            // TransactionFactory's own default 'tour_booking_id' => TourBooking::factory()
            // cascades a SEPARATE booking from the dispute's own booking_id, since Laravel
            // resolves each nested factory independently.
            $transactionBookingId = DB::table('transactions')->where('id', $dispute->transaction_id)->value('tour_booking_id');
            if ($transactionBookingId) {
                $this->createdBookingIds[] = $transactionBookingId;
            }
        }
    }

    protected function tearDown(): void
    {
        if (!empty($this->createdDisputeIds) || !empty($this->createdBookingIds)) {
            DB::table('disputes')
                ->where(function ($query) {
                    if (!empty($this->createdDisputeIds)) {
                        $query->orWhereIn('id', $this->createdDisputeIds);
                    }
                    if (!empty($this->createdBookingIds)) {
                        $query->orWhereIn('booking_id', $this->createdBookingIds);
                    }
                })
                ->delete();
        }

        if (!empty($this->createdTransactionIds) || !empty($this->createdBookingIds)) {
            DB::table('transactions')
                ->where(function ($query) {
                    if (!empty($this->createdTransactionIds)) {
                        $query->orWhereIn('id', $this->createdTransactionIds);
                    }
                    if (!empty($this->createdBookingIds)) {
                        $query->orWhereIn('tour_booking_id', $this->createdBookingIds);
                    }
                })
                ->delete();
        }

        if (!empty($this->createdBookingIds)) {
            DB::table('tour_bookings_transact')->whereIn('tour_booking_id', $this->createdBookingIds)->delete();
            DB::table('tour_booking_history')->whereIn('tour_booking_id', $this->createdBookingIds)->delete();
            DB::table('tour_bookings_master')->whereIn('id', $this->createdBookingIds)->delete();
        }

        if (!empty($this->createdAdminIds)) {
            DB::table('admins')->whereIn('id', $this->createdAdminIds)->delete();
        }

        parent::tearDown();
    }

    public function test_sends_new_dispute_notification()
    {
        Notification::fake();

        // Create admin user with permissions
        $admin = Admin::factory()->create(['status' => 'active', 'email' => 'admin@test.com']);
        $this->createdAdminIds[] = $admin->id;
        $admin->givePermissionTo('view-payment-dispute');

        // Create a dispute without relationships to avoid database issues
        $dispute = Dispute::factory()->create([
            'amount' => 100.00,
            'currency' => 'USD',
            'reason' => 'fraudulent',
            'status' => 'warning_needs_response',
        ]);
        $this->trackDispute($dispute);

        // Send notification
        $count = $this->notificationService->sendNewDisputeNotification($dispute);

        // Recipients may include users who hold the permission via a role in the
        // tenant DB — assert at least our admin was notified rather than an exact
        // count that would require clearing every role grant in the tenant.
        $this->assertGreaterThanOrEqual(1, $count);

        // Mail notifications are disabled — no Laravel notification is dispatched,
        // only the recipient count is returned.
        Notification::assertNothingSent();
    }

    public function test_sends_deadline_warning_notification()
    {
        Notification::fake();

        // Create admin user with permission
        $admin = Admin::factory()->create(['status' => 'active', 'email' => 'admin@test.com']);
        $this->createdAdminIds[] = $admin->id;
        $admin->givePermissionTo('view-payment-dispute');

        // Create dispute with deadline in 3 days
        $this->trackDispute(Dispute::factory()->create([
